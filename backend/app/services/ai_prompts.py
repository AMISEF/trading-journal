DEFAULT_LEVEL = "medium"


def normalize_level(value: str | None) -> str:
    """Map any client input to a known level (defaults to ``medium``)."""
    key = (value or "").strip().lower()
    return key if key in LEVELS else DEFAULT_LEVEL


def level_config(value: str | None) -> dict:
    return LEVELS[normalize_level(value)]


def level_block(value: str | None) -> str:
    """Persian instruction block describing the requested depth."""
    level = normalize_level(value)
    cfg = LEVELS[level]
    lines = [
        "## سطح تفکر درخواست‌شده",
        f"سطح: {cfg['label']} ({level}) — {cfg['note']}",
        f"حجم خروجی: حدود {cfg['words']} کلمه (کمی کمتر یا بیشتر اشکالی ندارد، ولی هیچ بخشی را حذف نکن).",
    ]
    if level == "low":
        lines.append(
            "در این سطح فشرده بنویس: هر بخش کوتاه، ولی دقیق و عددی. حداکثر ۲ نقطهٔ قوت و ۲ نقطهٔ ضعف."
        )
    elif level == "medium":
        lines.append("در این سطح تعادل را رعایت کن: ۲ تا ۳ نقطهٔ قوت و ۲ تا ۳ نقطهٔ ضعف با شواهد عددی.")
    elif level == "high":
        lines.append(
            "در این سطح عمیق‌تر برو: الگوهای تکرارشونده را بر حسب نماد، جهت، تایم‌فریم و سشن تفکیک کن."
        )
    elif level == "max":
        lines.append(
            "در این سطح کامل‌ترین تحلیل را بده: تفکیک عملکرد بر حسب نماد، جهت، سشن، تایم‌فریم، اهرم و سطح رعایت چک‌لیست، "
            "به‌علاوهٔ تحلیل روند بهبود یا افت در طول زمان."
        )
    else:  # ultra
        lines.append(
            "در این سطح علاوه بر همهٔ موارد بالا، تصاویر چارت خروج پیوست شده‌اند. هر تصویر را تکنیکال بخوان "
            "(ساختار بازار، ناحیهٔ ورود، جای حد ضرر، محل خروج) و در کارت امتیاز و تحلیل ضعف‌ها به آنچه در تصویر دیدی استناد کن "
            "(مثلاً «در چارت #۷۱ SOLUSDT حد ضرر دقیقاً روی سقف قبلی بوده»)."
        )
    return "\n".join(lines)


