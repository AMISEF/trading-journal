def level_block(value: str | None) -> str:
    """Persian instruction block describing the requested depth."""
    level = normalize_level(value)
    cfg = LEVELS[level]
    return "\n".join([
        "## سطح تفکر درخواست‌شده",
        "سطح: " + cfg["label"] + " (" + level + ") — " + cfg["note"],
        "حجم خروجی: حدود " + str(cfg["words"]) + " کلمه؛ هیچ بخشی را حذف نکن.",
        _LEVEL_EXTRA[level],
    ])


